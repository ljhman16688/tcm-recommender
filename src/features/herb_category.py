def clean_name(name):
    """名称清洗：去首尾空白 → 去炮制括号注记 → 错别字/碎片修正 → 清除开头粘连「或」。

    先剥括号注记再查 NAME_FIXES/集合，这样「瓜萎子(炒)」→「瓜萎子」→正名、
    「驴鞭(烫制)」→「驴鞭」→animal、「附子（黑顺片）」→「附子」都能命中。
    """
    name = str(name).strip()
    name = re.sub(r'[（(][^)）]*[)）]', '', name)
    name = name.strip()
    if name:
        name = NAME_FIXES.get(name, name)
    if name.startswith('或') and len(name) > 2:
        name = name[1:]
    return name


def classify(name):
    """按优先级判定条目类别。纯规则，无需词典。"""
    name = clean_name(name)
    if not name:
        return 'invalid'
    if name in MEDICINE_NAME:
        return 'invalid'
    if re.search(r'\d', name):
        return 'invalid'
    # 「含X/取X/约X/按X」剂量·工艺残片；含羞草 是正名，白名单保留
    if (name.startswith('含') and name != '含羞草') or name.startswith(('取', '约', '按')):
        return 'invalid'
    # 「X各」剂量残片（牛膝各/陈皮各…）
    if name.endswith('各'):
        return 'invalid'
    # 「A或B」备选残片（芪或膜荚黄芪…）；括号内的「或」属正常炮制说明，保留
    if '或' in name and '（' not in name and '(' not in name:
        return 'invalid'
    for kw in INVALID_KW:
        if kw in name:
            return 'invalid'
    if name in JUNK_NAMES:
        return 'invalid'
    if name in FOOD_NAMES:
        return 'food'
    if name in ANIMAL_NAMES:
        return 'animal'
    if name in CHEM_DRUG_NAMES:
        return 'chem'
    for kw in CHEM_KW:
        if kw in name:
            return 'chem'
    for kw in EXCIPIENT_KW:
        if kw in name:
            return 'excipient'
    if name in EXTRACT_TO_PARENT:
        # 冰片/樟脑 本身是药典单味药，算 herb；其余油/脑/浸膏算对应类
        if name in ('冰片', '樟脑'):
            return 'herb'
        return 'oil' if (name.endswith('油') or name.endswith('脑')) else 'extract'
    if any(name.endswith(s) for s in EXTRACT_SUFFIX):
        return 'extract'
    if name.endswith('油') or name.endswith('脑'):
        return 'oil'
    if name.endswith(COMPOUND_SUFFIX) or any(h in name for h in COMPOUND_HAS):
        return 'compound'
    return 'herb'


